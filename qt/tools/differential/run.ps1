# -DebugTool: the debug tool's answers against the release tool's, line for line. Adds a failure for any differing line (a
# missing line counts) and for a non-zero exit of the debug tool, and a summary line for the kind.
function Compare-DebugTool([string]$letter, [string[]]$arguments, [string]$inputFile, [string[]]$release) {
    try {
        $debug = Invoke-Side $debugExe $arguments $inputFile "debug-$letter"
    } catch {
        $failures.Add("${letter}: the debug tool failed: $($_.Exception.Message)")
        $summary.Add("${letter}: debug tool failed")
        return
    }
    $differences = 0
    if ($debug.Count -ne $release.Count -or -not [System.Linq.Enumerable]::SequenceEqual([string[]]$debug, [string[]]$release, [StringComparer]::Ordinal)) {
        for ($i = 0; $i -lt [Math]::Max($debug.Count, $release.Count); $i++) {
            $d = if ($i -lt $debug.Count) { $debug[$i] } else { $null }
            $r = if ($i -lt $release.Count) { $release[$i] } else { $null }
            if ($d -cne $r) {
                $differences++
                if ($script:shown -lt 12) {
                    $script:shown++
                    Write-Output "DEBUG DIFFERENCE [$letter] line ${i}"
                    Write-Output "   release: $r"
                    Write-Output "   debug:   $d"
                }
            }
        }
    }
    if ($debug.Count -ne $release.Count) { $failures.Add("${letter}: the debug tool wrote $($debug.Count) lines, the release tool $($release.Count)") }
    if ($differences -gt 0) { $failures.Add("${letter}: $differences lines of the debug tool differ from the release tool's") }
    $summary.Add("${letter}: debug tool $($debug.Count) lines, $differences differences from the release tool")
}

function ConvertFrom-Field([string]$field) {
    if ($field -eq '-') { return '(null)' }
    if ($field -eq '.') { return '(empty)' }
    if ($field -cnotmatch '^([0-9a-f]{4})+$') { return $field }
    $sb = [System.Text.StringBuilder]::new('"')
    for ($i = 0; $i -lt $field.Length; $i += 4) {
        $unit = [Convert]::ToInt32($field.Substring($i, 4), 16)
        if ($unit -ge 0x20 -and $unit -lt 0x7F -and $unit -ne 0x22 -and $unit -ne 0x5C) { [void]$sb.Append([char]$unit) }
        else { [void]$sb.Append(('\u{0:X4}' -f $unit)) }
    }
    return $sb.Append('"').ToString()
}
function ConvertFrom-Answer([string]$answer) {
    if ($null -eq $answer) { return '(no answer)' }
    return (($answer -split ' ') | ForEach-Object { ConvertFrom-Field $_ }) -join ' '
}

