        param($cases, $answers, $indexes)
        $errors = 0; $differs = 0; $same = 0
        foreach ($i in $indexes) {
            $answer = $answers[$i]
            if ($answer -ceq 'ERR') { $errors++ } elseif ($answer -ceq $cases[$i][1]) { $same++ } else { $differs++ }
        }
        Test-Share 'W' 'pn: answer ERR' $errors $indexes.Count 0.10
        Test-Share 'W' 'pn: answer differs from the input' $differs $indexes.Count 0.20
        Test-Share 'W' 'pn: answer equals the input' $same $indexes.Count 0.20
    }
    # pc dir name: success (not ERR) 60%
    pc = {
        param($cases, $answers, $indexes)
        $success = @($indexes | Where-Object { $answers[$_] -cne 'ERR' }).Count
        Test-Share 'W' 'pc: answer a path (not ERR)' $success $indexes.Count 0.60
    }
    # pf path: no file name (-) 5%; a file name with two or more dots 10%
    pf = {
        param($cases, $answers, $indexes)
        $none = @($indexes | Where-Object { $answers[$_] -ceq '-' }).Count
        $dots = @($indexes | Where-Object { $answers[$_] -cne 'ERR' -and (Get-UnitOccurrences $answers[$_] '002e') -ge 2 }).Count
        Test-Share 'W' 'pf: answer none (-)' $none $indexes.Count 0.05
        Test-Share 'W' 'pf: answer a name with two or more dots' $dots $indexes.Count 0.10
    }
    # px path: no name (the empty answer) 5%; a name that had two or more dots (the answer keeps one or more) 10%
    px = {
        param($cases, $answers, $indexes)
        $none = @($indexes | Where-Object { $answers[$_] -ceq '.' }).Count
        $dots = @($indexes | Where-Object { $answers[$_] -cne 'ERR' -and (Get-UnitOccurrences $answers[$_] '002e') -ge 1 }).Count
        Test-Share 'W' 'px: answer empty (no name)' $none $indexes.Count 0.05
        Test-Share 'W' 'px: answer of a name with two or more dots' $dots $indexes.Count 0.10
    }
    # ln bytes chunkSize...: inputs with `\r\n` 20%, with a lone `\r` (not before `\n`) 20%, with a lone `\n` (not after `\r`)
    # 20%; input that is not valid UTF-8 10%; input ending without a line ending (not empty) 30%; a chunk boundary inside a
    # multi-byte sequence (before a continuation byte that follows a byte of 80..FF) or between `\r` and `\n` 10%
    ln = {
        param($cases, $answers, $indexes)
        $strict = [System.Text.UTF8Encoding]::new($false, $true)
        $crlf = 0; $cr = 0; $lf = 0; $invalid = 0; $bare = 0; $split = 0
        foreach ($i in $indexes) {
            $hex = $cases[$i][1]
            if ($hex -ceq '.') { continue }
            if ($LnCrLf.IsMatch($hex)) { $crlf++ }
            if ($LnLoneCr.IsMatch($hex)) { $cr++ }
            if ($LnLoneLf.IsMatch($hex)) { $lf++ }
            try { [void]$strict.GetString([Convert]::FromHexString($hex)) } catch { $invalid++ }
            $last = $hex.Substring($hex.Length - 2)
            if ($last -cne '0a' -and $last -cne '0d') { $bare++ }
            # the chunk boundaries repeat with the period of the sizes: p is one when p mod period is a partial sum
            $sizes = @($cases[$i][2..($cases[$i].Count - 1)] | ForEach-Object { [int]$_ })
            $period = ($sizes | Measure-Object -Sum).Sum
            $sums = [System.Collections.Generic.HashSet[int]]::new()
            $sum = 0
            foreach ($s in $sizes) { $sum += $s; [void]$sums.Add($sum % $period) }
            foreach ($m in $LnSplitPoint.Matches($hex)) {
                if ($m.Index % 2 -ne 0) { continue }
                $p = $m.Index / 2 + 1
                if ($sums.Contains($p % $period)) { $split++; break }
            }
        }
        $n = $indexes.Count
        Test-Share 'W' 'ln: input with \r\n' $crlf $n 0.20
        Test-Share 'W' 'ln: input with a lone \r' $cr $n 0.20
        Test-Share 'W' 'ln: input with a lone \n' $lf $n 0.20
        Test-Share 'W' 'ln: input that is not valid UTF-8' $invalid $n 0.10
        Test-Share 'W' 'ln: input ending without a line ending' $bare $n 0.30
        Test-Share 'W' 'ln: a chunk boundary inside a multi-byte sequence or between \r and \n' $split $n 0.10
    }
    # st yt-dlp ffmpeg js: per tool, found and not found 20% each (Kotlin's answer); a js runtime whose version is just
    # above/below the minimum of its runtime (the first part that differs from the minimum differs by one) 10%, exactly at the
    # minimum shown apart; a start failure among the tools 2%
    st = {
        param($cases, $answers, $indexes)
        $found = @(0, 0, 0); $missing = @(0, 0, 0); $near = 0; $atMinimum = 0; $starts = 0
        foreach ($i in $indexes) {
            $tokens = $answers[$i] -split ' '
            for ($t = 0; $t -lt 3; $t++) { if ($tokens[3 * $t] -ceq '1') { $found[$t]++ } else { $missing[$t]++ } }
            if ($cases[$i][2] -ceq 'S' -or $cases[$i][5] -ceq 'S' -or $cases[$i][8] -ceq 'S') { $starts++ }
            $version = ConvertFrom-HexText $tokens[7]
            if ($null -ne $version -and $cases[$i][7] -cne '-') {
                $name = (ConvertFrom-HexText $cases[$i][7]).Split('\')[-1].ToLowerInvariant()
                if ($name.EndsWith('.exe')) { $name = $name.Substring(0, $name.Length - 4) }
                $minimum = if ($name -ceq 'deno') { @(2, 3, 0) } else { @(22, 0, 0) }
                $parts = @($version.Split('.') | ForEach-Object {
                    $value = [long]0; $digits = 0
                    foreach ($c in $_.ToCharArray()) {
                        if (-not [char]::IsDigit($c)) { break }
                        $value = $value * 10 + [long][char]::GetNumericValue($c); $digits++
                        if ($value -gt [int]::MaxValue) { $value = 0; break }
                    }
                    $value
                })
                # just above/below: the first part that differs from the minimum differs by one; exactly at the minimum
                # (no part differs) is counted apart
                $isAt = $true; $isNear = $false
                for ($k = 0; $k -lt 3; $k++) {
                    $actual = if ($k -lt $parts.Count) { $parts[$k] } else { 0 }
                    if ($actual -ne $minimum[$k]) { $isAt = $false; $isNear = [Math]::Abs($actual - $minimum[$k]) -eq 1; break }
                }
                if ($isNear) { $near++ }
                if ($isAt) { $atMinimum++ }
            }
        }
        $n = $indexes.Count
        $names = @('yt-dlp', 'ffmpeg', 'js runtime')
        for ($t = 0; $t -lt 3; $t++) {
            Test-Share 'W' "st: $($names[$t]) found" $found[$t] $n 0.20
            Test-Share 'W' "st: $($names[$t]) not found" $missing[$t] $n 0.20
        }
        Test-Share 'W' 'st: js runtime version just above/below the minimum' $near $n 0.10
        Test-Share 'W' 'st: js runtime version exactly at the minimum (shown only)' $atMinimum $n 0
        Test-Share 'W' 'st: a tool that does not start' $starts $n 0.02
    }
    # up yt-dlp: OK 30%, ERR 30% (Kotlin's answer); a start failure 2%
    up = {
        param($cases, $answers, $indexes)
        $ok = @($indexes | Where-Object { $answers[$_].StartsWith('OK ') }).Count
        $err = @($indexes | Where-Object { $answers[$_].StartsWith('ERR ') }).Count
        $starts = @($indexes | Where-Object { $cases[$_][2] -ceq 'S' }).Count
        Test-Share 'W' 'up: answer OK' $ok $indexes.Count 0.30
        Test-Share 'W' 'up: answer ERR' $err $indexes.Count 0.30
        Test-Share 'W' 'up: yt-dlp does not start' $starts $indexes.Count 0.02
    }
    # fn name: each answer (accepted 1, rejected 0) 25%
    fn = {
        param($cases, $answers, $indexes)
        $accepted = @($indexes | Where-Object { $answers[$_] -ceq '1' }).Count
        $rejected = @($indexes | Where-Object { $answers[$_] -ceq '0' }).Count
        Test-Share 'W' 'fn: answer 1 (accepted)' $accepted $indexes.Count 0.25
        Test-Share 'W' 'fn: answer 0 (rejected)' $rejected $indexes.Count 0.25
    }
    # lf artist title album duration maxRequests timeout step... (Kotlin's answer: OK hex | NULL, N count, C count, U urls):
    # lyrics found 15%, not found 30%; a request to /search 40%; a request started the cool-down 10%; the cap cut the lookup
    # short 5%;
    # a query with a character outside ASCII 20%, with one of `& = # + %` or a space 10%, with an unpaired surrogate 2%; a
    # requested answer with a record that has a field of the wrong type 10%, with a record whose instrumental flag is in an
    # odd case 10% (counted apart: kotlinx reads it as a boolean, so it is not a wrong type), with a body that is
    # not JSON 5%; a requested /search answer with two or more records 15%.
    # A request of the first call started the cool-down exactly when it ended in Stop (the only way a request starts it): the
    # last request it made was answered 429, 502, 503 or 504 (with any body) or failed to connect, timed out or found no host
    # (C, T, U). Checked both ways (it fails the run otherwise): the second call made no request in every such case, and at
    # least one in every other case of a query that is not blank with maxRequests >= 1. A case whose request timeout is not
    # positive (0 or N) counts on neither side and not in the check: the provider then starts the cool-down without a
    # request (as Kotlin does), but neither call sends anything either way, so it cannot be seen. The share's denominator
    # is still every lf case.
    # The cap cut the lookup short exactly when one call with maxRequests + 1 on the same steps (C) made more than
    # maxRequests requests: the two calls are the same up to the cap, so the wider one makes a further request only if the
    # first call was stopped by the cap.
    lf = {
        param($cases, $answers, $indexes)
        $found = 0; $none = 0; $search = 0; $coolDown = 0; $cap = 0; $nonAscii = 0; $special = 0; $lone = 0; $wrong = 0; $notJson = 0
        $several = 0; $coolDownButAsked = 0; $oddCase = 0
        foreach ($i in $indexes) {
            $case = $cases[$i]
            $tokens = $answers[$i] -split ' '
            if ($tokens[0] -ceq 'OK') { $found++ } elseif ($tokens[0] -ceq 'NULL') { $none++ }
            $at = [Array]::IndexOf($tokens, 'N')
            $second = [int]$tokens[$at + 1]
            $wider = [int]$tokens[$at + 3]
            $urls = @(if ($tokens.Count -gt $at + 5) { $tokens[($at + 5)..($tokens.Count - 1)] })
            if (@($urls | Where-Object { $_.StartsWith($LfSearchHex, [StringComparison]::Ordinal) }).Count -gt 0) { $search++ }
            $max = [int]$case[5]
            # a request timeout that is not positive (0 or N): neither call sends anything, so whether the cool-down started
            # cannot be seen; such a case is counted on neither side of the statistic and its check
            if ($case[6] -ceq 'D') {
                $started = $false
                if ($urls.Count -gt 0) {
                    $last = if (7 + $urls.Count - 1 -lt $case.Count) { $case[7 + $urls.Count - 1] } else { '404:.' }
                    $started = $LfStopStep.IsMatch($last)
                }
                if ($started) { $coolDown++; if ($second -ne 0) { $coolDownButAsked++ } }
                # the other way round: without a cool-down, a query that is not blank with maxRequests >= 1 is asked again
                elseif ($second -eq 0 -and $max -gt 0 -and -not (Test-KotlinBlank $case[1]) -and -not (Test-KotlinBlank $case[2])) { $coolDownButAsked++ }
            }
            if ($max -gt 0 -and $wider -gt $max) { $cap++ }
            $fields = @($case[1], $case[2], $case[3])
            if (@($fields | Where-Object { $LfNonAsciiHex.IsMatch($_) }).Count -gt 0) { $nonAscii++ }
            if (@($fields | Where-Object { $LfSpecialHex.IsMatch($_) }).Count -gt 0) { $special++ }
            if (@($fields | Where-Object { $LoneHexPattern.IsMatch($_) }).Count -gt 0) { $lone++ }
            # the steps of the first call's requests (step k answers request k)
            $hasWrong = $false; $hasNotJson = $false; $hasSeveral = $false; $hasOddCase = $false
            for ($k = 0; $k -lt $urls.Count -and 7 + $k -lt $case.Count; $k++) {
                $step = $case[7 + $k]
                if (-not $step.StartsWith('200:') -or $step -ceq '200:L') { continue }
                $hex = $step.Substring(4)
                $bytes = [byte[]]::new(0)
                if ($hex -cne '.') { $bytes = [Convert]::FromHexString($hex) }
                $text = [System.Text.Encoding]::UTF8.GetString($bytes)
                if ($LfWrongType.IsMatch($text)) { $hasWrong = $true }
                if ($LfOddCaseFlag.IsMatch($text)) { $hasOddCase = $true }
                $root = $null
                $strictText = $null
                try { $strictText = $LfStrictUtf8.GetString($bytes) } catch { }
                if ($null -ne $strictText) {
                    try {
                        $document = [System.Text.Json.JsonDocument]::Parse($LfOddLiteral.Replace($strictText, ':0'))
                        $document.Dispose()
                    } catch { $hasNotJson = $true }
                }
                if ($urls[$k].StartsWith($LfSearchHex, [StringComparison]::Ordinal) -and [LfScan]::ObjectsInRootArray($text) -ge 2) { $hasSeveral = $true }
            }
            if ($hasWrong) { $wrong++ }
            if ($hasNotJson) { $notJson++ }
            if ($hasSeveral) { $several++ }
            if ($hasOddCase) { $oddCase++ }
        }
        $n = $indexes.Count
        Test-Share 'W' 'lf: lyrics found' $found $n 0.15
        Test-Share 'W' 'lf: no lyrics' $none $n 0.30
        Test-Share 'W' 'lf: a request to /search' $search $n 0.40
        Test-Share 'W' 'lf: a request started the cool-down' $coolDown $n 0.10
        Write-Host "  W: lf: check, not a threshold: cases where the cool-down rule and the second call disagree: $coolDownButAsked"
        if ($coolDownButAsked -gt 0) { "W: lf: $coolDownButAsked cases where the cool-down rule of the statistic and the second call disagree (the rule is wrong)" }
        Test-Share 'W' 'lf: the cap cut the lookup short' $cap $n 0.05
        Test-Share 'W' 'lf: a query with a character outside ASCII' $nonAscii $n 0.20
        Test-Share 'W' 'lf: a query with one of & = # + % or a space' $special $n 0.10
        Test-Share 'W' 'lf: a query with an unpaired surrogate' $lone $n 0.02
        Test-Share 'W' 'lf: a requested answer with a record that has a field of the wrong type' $wrong $n 0.10
        Test-Share 'W' 'lf: a requested answer with a record whose instrumental flag is in an odd case' $oddCase $n 0.10
        Test-Share 'W' 'lf: a requested answer whose body is not JSON' $notJson $n 0.05
        Test-Share 'W' 'lf: a requested /search answer with two or more records' $several $n 0.15
    }
    # jb: the whole job (the plan's `W jb` table; thresholds verbatim, as shares of the jb cases). Everything is counted from
    # the Kotlin answer (its events, the rank of each yt-dlp run, each put) and, where an answer says which script entry a
    # call took (scripts are consumed in call order, then their last entry again), from that entry of the case.
    jb = {
        param($cases, $answers, $indexes, $portAnswers)
        $alignedPercent = 0; $alignedTail = 0
        $completed = 0; $failedJob = 0; $skipped = 0; $failedItem = 0; $retried = 0; $gaveUp = 0; $reparsed = 0; $sameName = 0
        $alreadyExists = 0; $existsSkip = 0; $denied = 0; $diskFull = 0; $progress3 = 0; $notFinite = 0; $override = 0; $badInfo = 0
        $outcomes = @{ DESCRIPTION = 0; ONLINE = 0; NOT_FOUND = 0; SEARCH_OFF = 0 }
        foreach ($i in $indexes) {
            $case = $cases[$i]
            $s = Get-JbSections $answers[$i]
            $n = [int]$case[7]
            $at = 8 + 7 * $n
            $lowByRank = @{}
            for ($k = 0; $k -lt $n; $k++) { $lowByRank[$case[8 + 7 * $k]] = $case[8 + 7 * $k + 6] -ceq '1' }
            $metaScript = $case[$at].Split(',')
            $ytDlpScript = $case[$at + 1].Split(',')
            $putScript = $case[$at + 4].Split(',')
            $events = $s['E']
            $done = @($events | Where-Object { $_.StartsWith('J,') })
            if ($done.Count -eq 1) {
                if ($done[0].StartsWith('J,COMPLETED,')) { $completed++ } elseif ($done[0].StartsWith('J,FAILED,')) { $failedJob++ }
            }
            if (@($events | Where-Object { $_.StartsWith('K,') }).Count -gt 0) { $skipped++ }
            $failures = @{}
            foreach ($e in $events) { if ($e.StartsWith('F,')) { $parts = $e.Split(','); $failures[$parts[1]] = $parts[2] } }
            if ($failures.Count -gt 0) { $failedItem++ }
            # retries: a rank with two or more yt-dlp runs; giving up: three runs, the third one transient, and the item failed
            $runsByRank = @{}
            for ($p = 0; $p -lt $s['Y'].Count; $p++) {
                $rank = $s['Y'][$p]
                if (-not $runsByRank.ContainsKey($rank)) { $runsByRank[$rank] = [System.Collections.Generic.List[int]]::new() }
                $runsByRank[$rank].Add($p)
            }
            if (@($runsByRank.Values | Where-Object { $_.Count -ge 2 }).Count -gt 0) { $retried++ }
            $gave = $false
            foreach ($rank in $runsByRank.Keys) {
                $runs = $runsByRank[$rank]
                if ($runs.Count -ne 3 -or -not $failures.ContainsKey($rank)) { continue }
                $entry = $ytDlpScript[[Math]::Min($runs[2], $ytDlpScript.Count - 1)].Split('/')
                if ($entry[0] -cne '0' -and (Test-JbTransient $entry[5])) { $gave = $true }
            }
            if ($gave) { $gaveUp++ }
            # each lyrics outcome once per case
            $seen = @{}
            foreach ($e in $events) { if ($e -cmatch '^D,\d+,[^,]+,(DESCRIPTION|ONLINE|NOT_FOUND|SEARCH_OFF)$') { $seen[$Matches[1]] = $true } }
            foreach ($outcome in $seen.Keys) { $outcomes[$outcome]++ }
            # lowConfidence parsed again: the items that started, in order; each lowConfidence one took the next metadata answer
            $metaAt = 0; $again = $false; $names = @{}; $dup = $false
            foreach ($e in $events) {
                if (-not $e.StartsWith('S,')) { continue }
                $parts = $e.Split(',')
                if ($lowByRank[$parts[1]]) {
                    if ($metaScript[[Math]::Min($metaAt, $metaScript.Count - 1)] -cne '-') { $again = $true }
                    $metaAt++
                }
                if ($names.ContainsKey($parts[3])) { $dup = $true } else { $names[$parts[3]] = $true }
            }
            if ($again) { $reparsed++ }
            if ($dup) { $sameName++ }
            # puts: the entry each put took, and what the item reported
            $exists = $false; $existsSkipped = $false; $deny = $false; $full = $false
            $skippedRanks = @{}
            foreach ($e in $events) { if ($e.StartsWith('K,')) { $skippedRanks[$e.Split(',')[1]] = $true } }
            for ($p = 0; $p -lt $s['P'].Count; $p++) {
                $rank = $s['P'][$p].Split('/')[0]
                $entry = $putScript[[Math]::Min($p, $putScript.Count - 1)]
                if ($entry -cmatch '^[Aa]') {
                    $exists = $true
                    # skipped after the put: an item skipped up front never reaches its put
                    if ($skippedRanks.ContainsKey($rank)) { $existsSkipped = $true }
                }
                if ($entry.StartsWith('F') -and $failures.ContainsKey($rank)) {
                    if ($failures[$rank] -ceq $JbNoPermissionHex) { $deny = $true }
                    if ($failures[$rank] -ceq $JbDiskFullHex) { $full = $true }
                }
            }
            if ($exists) { $alreadyExists++ }
            if ($existsSkipped) { $existsSkip++ }
            if ($deny) { $denied++ }
            if ($full) { $diskFull++ }
            $progressEvents = @($events | Where-Object { $_.StartsWith('P,') })
            if ($progressEvents.Count -ge 3) { $progress3++ }
            if (@($progressEvents | Where-Object { $_.EndsWith(',N') }).Count -gt 0) { $notFinite++ }
            if ($case[4] -cne '-' -and -not (Test-KotlinBlank $case[4]) -and $s['M'].Count -gt 0) { $override++ }
            # info files read: a run that exited with 0 and wrote the m4a goes on to read its info file
            $bad = $false
            for ($p = 0; $p -lt $s['Y'].Count; $p++) {
                $entry = $ytDlpScript[[Math]::Min($p, $ytDlpScript.Count - 1)].Split('/')
                if ($entry[0] -ceq '0' -and $entry[1] -ceq '1' -and -not (Test-JbInfoReadable $entry[3])) { $bad = $true }
            }
            if ($bad) { $badInfo++ }
            # (shown only) the cases whose two answers differ before the alignment and agree after it, by the difference aligned
            if ($null -ne $portAnswers -and $answers[$i] -cne $portAnswers[$i] -and $null -ne $portAnswers[$i] -and
                (Format-JbFolded $case $answers[$i] 'kotlin') -ceq (Format-JbFolded $case $portAnswers[$i] 'port')) {
                if (@($events | Where-Object { $_ -cmatch '^P,-?\d+,[DF],N$' }).Count -gt 0) { $alignedPercent++ }
                if ((Format-JbPercents $answers[$i]) -cne $portAnswers[$i]) { $alignedTail++ }
            }
        }
        $n = $indexes.Count
        Test-Share 'W' 'jb: Completed' $completed $n 0.40
        Test-Share 'W' 'jb: Failed' $failedJob $n 0.10
        Test-Share 'W' 'jb: a case with ItemSkipped' $skipped $n 0.15
        Test-Share 'W' 'jb: a case with ItemFailed' $failedItem $n 0.20
        Test-Share 'W' 'jb: a retry happened' $retried $n 0.10
        Test-Share 'W' 'jb: given up after two retries' $gaveUp $n 0.03
        Test-Share 'W' 'jb: ItemDone with lyrics DESCRIPTION' $outcomes['DESCRIPTION'] $n 0.05
        Test-Share 'W' 'jb: ItemDone with lyrics ONLINE' $outcomes['ONLINE'] $n 0.05
        Test-Share 'W' 'jb: ItemDone with lyrics NOT_FOUND' $outcomes['NOT_FOUND'] $n 0.05
        Test-Share 'W' 'jb: ItemDone with lyrics SEARCH_OFF' $outcomes['SEARCH_OFF'] $n 0.05
        Test-Share 'W' 'jb: a lowConfidence item parsed again' $reparsed $n 0.10
        Test-Share 'W' 'jb: the same file name twice or more in one job' $sameName $n 0.05
        Test-Share 'W' 'jb: a put that answered AlreadyExists' $alreadyExists $n 0.03
        # (not in the plan's table: added by the Task 4 review, so that the skip of decision 5's second row is reached)
        Test-Share 'W' 'jb: a put that answered AlreadyExists and the item was skipped' $existsSkip $n 0.02
        Test-Share 'W' 'jb: a put denied access' $denied $n 0.03
        Test-Share 'W' 'jb: a put found the disk full' $diskFull $n 0.03
        Test-Share 'W' 'jb: three or more Progress events' $progress3 $n 0.20
        Test-Share 'W' 'jb: a percent that is not finite' $notFinite $n 0.02
        Test-Share 'W' 'jb: an album override (tags written)' $override $n 0.10
        Test-Share 'W' 'jb: an info file read that was broken or missing' $badInfo $n 0.10
        Write-Host "  W: jb: shown only: cases equal only after the alignment: $alignedPercent with a percent that is not finite (Kotlin N), $alignedTail with an AlreadyExists tail that the alignment drops"
    }
}
# Helpers of the W lf statistics (for counting only; the answers are compared exactly). The URL of a /search request as hex;
# on a field's hex, a unit outside ASCII and one of `& = # + %` or a space; on a decoded body, a record field of the wrong
# type (a duration that is not a plain number or null, an instrumental that is not true, false or null in any case, a string
# field that is not a string or null) and, apart from it, an instrumental flag spelled in an odd case (true or false as
# kotlinx reads them, String.equals(ignoreCase = true), where U+017F counts as s: `TRUE`, `fAlSe`, `fal` U+017F `e`...);
# the unquoted odd literals that kotlinx reads and System.Text.Json does not (replaced by 0 before the strict parse that decides "not JSON"; the replaced run never holds `"` or `\`, so a valid string stays valid);
# a step that makes the provider stop and start its cool-down. Test-KotlinBlank: Kotlin's isBlank of a field's hex.
$LfStopStep = [regex]::new('^(?:(?:429|502|503|504):.*|C|T|U)$', 'Compiled')
function Test-KotlinBlank([string]$field) {
    if ($field -ceq '.') { return $true }
    if ($field -ceq '-') { return $false }
    for ($i = 0; $i -lt $field.Length; $i += 4) {
