# ---- table kinds ----
function Invoke-TableKind([string]$letter) {
    $mode = $Statistics[$letter].Table
    $kotlin = Invoke-Side $java ($oracleArgs + $mode) $null "kotlin-$mode"
    $port = Invoke-Side $tool @($mode) $null "port-$mode"
    if ($DebugTool) { Compare-DebugTool $letter @($mode) $null $port }
    $mismatches = 0
    if ($kotlin.Count -ne $port.Count) { $failures.Add("${letter}: Kotlin wrote $($kotlin.Count) lines, the port $($port.Count)") }
    # the common case first: identical tables (one fast comparison instead of a loop over a million lines)
    if ($kotlin.Count -ne $port.Count -or -not [System.Linq.Enumerable]::SequenceEqual([string[]]$kotlin, [string[]]$port, [StringComparer]::Ordinal)) {
        for ($i = 0; $i -lt [Math]::Max($kotlin.Count, $port.Count); $i++) {
            $k = if ($i -lt $kotlin.Count) { $kotlin[$i] } else { $null }
            $p = if ($i -lt $port.Count) { $port[$i] } else { $null }
            if ($k -cne $p) {
                $mismatches++
                if ($script:shown -lt 12) {
                    $script:shown++
                    Write-Output ('MISMATCH [{0}] line {1} (U+{1:X4} for X; a U, B or Z line starts with its code point)' -f $letter, $i)
                    Write-Output "   kotlin: $k"
                    Write-Output "   port:   $p"
                }
            }
        }
    }
    if ($mismatches -gt 0) { $failures.Add("${letter}: $mismatches mismatches") }
    foreach ($message in @(& $Statistics[$letter].Check $kotlin)) { if ($message) { $failures.Add($message) } }
    $unit = if ($letter -eq 'X') { 'units' } elseif ($letter -eq 'M') { 'constants' } elseif ('U', 'B', 'Z' -ccontains $letter) { 'code points' } else { 'lines' }
    $summary.Add("${letter}: $($kotlin.Count) $unit, $mismatches mismatches")
}

# ---- case kinds: one kind at a time ----
function Invoke-CaseKind([string]$letter) {
    $generated = Invoke-Side $tool @('gen', $letter, "$PerKind", "$Seed") $null "gen-$letter"
    if ($generated.Count -ne $PerKind) { $failures.Add("${letter}: xgs-diff generated $($generated.Count) cases, not $PerKind") }
    $caseFile = Join-Path $work "cases-$letter.txt"
    [System.IO.File]::WriteAllText($caseFile, (($generated -join "`n") + "`n"), [System.Text.Encoding]::ASCII)
    $kotlin = Invoke-Side $java $oracleArgs $caseFile "kotlin-answers-$letter"
    $port = Invoke-Side $tool @('answer') $caseFile "port-answers-$letter"
    if ($DebugTool) { Compare-DebugTool $letter @('answer') $caseFile $port }
    Remove-Item -LiteralPath $caseFile
    if ($kotlin.Count -ne $generated.Count) { $failures.Add("${letter}: Kotlin answered $($kotlin.Count) of $($generated.Count) cases") }
    if ($port.Count -ne $generated.Count) { $failures.Add("${letter}: the port answered $($port.Count) of $($generated.Count) cases") }
    $cases = [System.Collections.Generic.List[object]]::new($generated.Count)
    $answers = [System.Collections.Generic.List[string]]::new($generated.Count)
    $portAnswers = [System.Collections.Generic.List[string]]::new($generated.Count)
    $mismatches = 0; $unknown = 0
    $folding = $Folding[$letter]
    for ($i = 0; $i -lt $generated.Count; $i++) {
        $fields = $generated[$i].Split("`t")
        $generated[$i] = $null   # the split fields are kept; release the line
        if ($fields[0] -cne $letter) {
            # an empty or foreign case line (a generator bug): report it and go on, so the failure list is complete
            $failures.Add("${letter}: case line #$i is empty or starts with '$($fields[0])'")
            continue
        }
        $k = if ($i -lt $kotlin.Count) { $kotlin[$i] } else { $null }
        $p = if ($i -lt $port.Count) { $port[$i] } else { $null }
        $rest = [string[]]$(if ($fields.Count -gt 1) { $fields[1..($fields.Count - 1)] } else { @() })
        $cases.Add($rest)
        $answers.Add($k)
        $portAnswers.Add($p)
        if (($null -ne $k -and $k.StartsWith('?')) -or ($null -ne $p -and $p.StartsWith('?'))) { $unknown++ }
        $kc = $k; $pc = $p
        if ($folding) {
            $kc = & $folding.Fold $rest $k 'kotlin'
            $pc = & $folding.Fold $rest $p 'port'
        }
        if ($kc -cne $pc) {
            $mismatches++
            if ($script:shown -lt 12) {
                $script:shown++
                Write-Output ("MISMATCH #$i [$letter] input: " + (($rest | ForEach-Object { ConvertFrom-Field $_ }) -join ' , '))
                Write-Output "   kotlin: $(ConvertFrom-Answer $k)"
                Write-Output "   port:   $(ConvertFrom-Answer $p)"
            }
        }
    }
    $generated = $null; $kotlin = $null; $port = $null
    if ($mismatches -gt 0) { $failures.Add("${letter}: $mismatches mismatches") }
    if ($unknown -gt 0) { $failures.Add("${letter}: $unknown answers of '?' (a side does not know the case)") }
    if ($cases.Count -eq 0) { $failures.Add("${letter}: no cases") }
    foreach ($message in @(& $Statistics[$letter].Check $cases.ToArray() $answers.ToArray() $portAnswers.ToArray())) { if ($message) { $failures.Add($message) } }
    if ($folding) { Write-Output $folding.Note }
    $summary.Add("${letter}: $($cases.Count) cases, $mismatches mismatches")
}

