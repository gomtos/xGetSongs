# ---- statistics: one entry per kind ----
# Table kinds: Table = the mode both sides print; Check gets the Kotlin answers. Case kinds: Check gets the cases (each the
# array of fields after the kind letter), the Kotlin answers and the port's answers. A check returns failure messages (none =
# reached).
# The protocol's thresholds are counts for 10000 cases; here they are fractions of the cases, so any -PerKind works.
function Get-Share([int]$count, [int]$total) { if ($total -eq 0) { 0 } else { $count / $total } }
# Shows a measured share (so a passing run says how far above its threshold it is) and returns the failure message when it
# is below $min.
function Test-Share([string]$kind, [string]$label, [int]$count, [int]$total, [double]$min) {
    $share = Get-Share $count $total
    Write-Host ('  {0}: {1}: {2} of {3} = {4:P1} (needs {5:0.##%})' -f $kind, $label, $count, $total, $share, $min)
    if ($share -lt $min) { "${kind}: $label is $count of $total cases (needs $('{0:0.##%}' -f $min))" }
}
# Helpers of the F/D/G statistics, on the hex notation of a field ('-' null, '.' empty, else 4 hex digits per UTF-16 unit).
function Get-UnitCount([string]$field) { if ($field -ceq '-' -or $field -ceq '.') { 0 } else { $field.Length / 4 } }
function Test-SurrogateInRange([string]$field, [int]$from, [int]$to) {
    # a UTF-16 surrogate unit (D800..DFFF) among the units from..to (0-based, inclusive)
    if ($field -ceq '-' -or $field -ceq '.') { return $false }
    for ($i = [Math]::Max(0, $from); $i -le [Math]::Min($to, $field.Length / 4 - 1); $i++) {
        if ($field.Substring($i * 4, 4) -cmatch '^d[89a-f]') { return $true }
    }
    return $false
}
function Test-BlankOnly([string]$field) {
    # not null, not empty, and nothing but white space (the white space strings of nullable() are 1 to 4 units)
    if ($field -ceq '-' -or $field -ceq '.' -or $field.Length -gt 64) { return $false }
    for ($i = 0; $i -lt $field.Length; $i += 4) {
        # Kotlin's Char.isWhitespace(): .NET's IsWhiteSpace plus U+001C..001F (and without U+0085, which Java does not count)
        $unit = [Convert]::ToInt32($field.Substring($i, 4), 16)
        $white = ($unit -ge 0x1C -and $unit -le 0x1F) -or ($unit -ne 0x85 -and [char]::IsWhiteSpace([char]$unit))
        if (-not $white) { return $false }
    }
    return $true
}
function Get-OptionalShares($fields) {
    # null, empty and white-space-only counts of an optional field over all cases
    $null_ = @($fields | Where-Object { $_ -ceq '-' }).Count
    $empty = @($fields | Where-Object { $_ -ceq '.' }).Count
    $blank = @($fields | Where-Object { Test-BlankOnly $_ }).Count
    return @{ null = $null_; empty = $empty; blank = $blank }
}
function Test-OptionalShares([string]$kind, [string]$name, $fields) {
    $total = $fields.Count
    $shares = Get-OptionalShares $fields
    foreach ($which in 'null', 'empty', 'blank') { Test-Share $kind "$name is $which" $shares[$which] $total 0.05 }
}
