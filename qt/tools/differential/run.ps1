# a case with a C++ answer longer than the Kotlin one, or with fewer of a placeholder (0 when nothing differs)
function Test-LeakDirection([string]$kind, $answers, $portAnswers) {
    $leaks = 0
    for ($i = 0; $i -lt $answers.Count; $i++) {
        $k = $answers[$i]; $p = $portAnswers[$i]
        if ($null -eq $k -or $null -eq $p) { continue }
        if ($p.Length -gt $k.Length -or
            (Get-AlignedCount $p $PathPlaceholderHex) -lt (Get-AlignedCount $k $PathPlaceholderHex) -or
            (Get-AlignedCount $p $FileNamePlaceholderHex) -lt (Get-AlignedCount $k $FileNamePlaceholderHex)) { $leaks++ }
    }
    Write-Host "  ${kind}: diagnostic, not a threshold: leak direction (C++ answer longer, or with fewer placeholders, than Kotlin's): $leaks of $($answers.Count)"
    if ($leaks -gt 0) { "${kind}: $leaks answers redact less than Kotlin's" }
}
