# how many times $needle occurs in an answer's hex at a unit boundary
function Get-AlignedCount([string]$answer, [string]$needle) {
    if (-not $answer -or -not $answer.StartsWith('OK ')) { return 0 }
    $hex = $answer.Substring(3)
    $count = 0
    $at = $hex.IndexOf($needle, [StringComparison]::Ordinal)
    while ($at -ge 0) {
        if ($at % 4 -eq 0) { $count++; $at = $hex.IndexOf($needle, $at + $needle.Length, [StringComparison]::Ordinal) }
        else { $at = $hex.IndexOf($needle, $at + 1, [StringComparison]::Ordinal) }
    }
    return $count
}
