                if ($TwoPathsArrow.IsMatch($raw)) { $arrow++ }
                if ($PathThenReason.IsMatch($raw)) { $reason++ }
                if ($Decoy.IsMatch($raw)) {
                    $decoys++
                    if (-not $AnyPath.IsMatch($raw)) {
                        $decoyOnly++
                        if ((Get-AlignedCount $answers[$i] $PathPlaceholderHex) -eq 0) { $decoyOnlyClean++ }
                    }
                }
                if ((Get-UnitCount $field) -gt 4000) {
                    $long++
                    if (Test-SurrogateInRange $field 3999 3999) { $longSurrogate++ }
                    # a path that starts within the 200 units before the cut and has no line break or forbidden character
                    # up to unit 4000
                    $window = $raw.Substring(3800, 201)
                    if ([regex]::IsMatch($window, "$PathStart(?:$PartChar|[\\/])*$")) { $longPath++ }
                }
                if ($PairHexPattern.IsMatch($field)) { $pair++ }
                if ($LoneHexPattern.IsMatch($field)) { $lone++ }
            }
            foreach ($name in $PathForms.Keys) { Test-Share 'R' "input with $name" $forms[$name] $total 0.03 }
            Test-Share 'R' 'input with two paths joined by , or ;' $listed $total 0.05
            Test-Share 'R' 'input with two paths joined by ->' $arrow $total 0.05
            Test-Share 'R' 'input with a : reason after a path' $reason $total 0.05
            Test-Share 'R' 'input with a decoy' $decoys $total 0.10
            Test-Share 'R' 'decoy-only input whose Kotlin answer has no <경로>' $decoyOnlyClean $decoyOnly 0.90
            Test-Share 'R' 'input over 4000 units' $long $total 0.03
            Test-Share 'R' 'input over 4000 units with a surrogate unit at unit 3999' $longSurrogate $total 0.01
            Test-Share 'R' 'input over 4000 units with a path running over the cut' $longPath $total 0.01
            Test-Share 'R' 'input with a surrogate pair' $pair $total 0.05
            Test-Share 'R' 'input with an unpaired surrogate' $lone $total 0.02
            Test-LeakDirection 'R' $answers $portAnswers
        }
    }
    N = @{
        # fields: text name1 [name2 ...]. Answers with <파일명> 20%; a name found in another case than given 5%; a name
        # shorter than 3 units or blank 5%; a name inside a path 5%; one name a prefix of another 3%; and the leak direction
        Check = {
            param($cases, $answers, $portAnswers)
            $total = $cases.Count
            $with = @($answers | Where-Object { (Get-AlignedCount $_ $FileNamePlaceholderHex) -gt 0 }).Count
            Test-Share 'N' 'answer with <파일명>' $with $total 0.20
            $otherCase = 0; $short = 0; $inPath = 0; $prefix = 0
            for ($i = 0; $i -lt $total; $i++) {
                $raw = ConvertFrom-HexText $cases[$i][0]
                if ($null -eq $raw) { $raw = '' }
                $names = @($cases[$i][1..($cases[$i].Count - 1)] | ForEach-Object { $n = ConvertFrom-HexText $_; if ($null -eq $n) { '' } else { $n } })
                $sawOther = $false; $sawShort = $false; $sawInPath = $false; $sawPrefix = $false
                foreach ($name in $names) {
                    $stem = $(if ($name.LastIndexOf('.') -ge 0) { $name.Substring(0, $name.LastIndexOf('.')) } else { $name })
                    if ($name.Length -lt 3 -or $name.Trim($KotlinWhitespace).Length -eq 0) { $sawShort = $true; continue }
                    foreach ($form in @($name, $stem)) {
                        if ($form.Length -lt 3 -or $form.Trim($KotlinWhitespace).Length -eq 0) { continue }
                        $escaped = [regex]::Escape($form)
                        $ci = [regex]::Matches($raw, $escaped, 'IgnoreCase, CultureInvariant').Count
                        $cs = [regex]::Matches($raw, $escaped).Count
                        if ($ci -gt $cs) { $sawOther = $true }
                        if ([regex]::IsMatch($raw, "[\\/]$escaped", 'IgnoreCase, CultureInvariant')) { $sawInPath = $true }
                    }
                    foreach ($other in $names) {
                        if ($other.Length -gt $name.Length -and $other.StartsWith($name, [StringComparison]::Ordinal)) { $sawPrefix = $true }
                    }
                }
                if ($sawOther) { $otherCase++ }
                if ($sawShort) { $short++ }
                if ($sawInPath) { $inPath++ }
                if ($sawPrefix) { $prefix++ }
            }
            Test-Share 'N' 'a name found in another case than given' $otherCase $total 0.05
            Test-Share 'N' 'a name shorter than 3 units or blank' $short $total 0.05
            Test-Share 'N' 'a name inside a path' $inPath $total 0.05
            Test-Share 'N' 'one name a prefix of another' $prefix $total 0.03
            Test-LeakDirection 'N' $answers $portAnswers
        }
    }
    C = @{
        Check = {
            param($cases, $answers)
            $total = $answers.Count
            $groups = [ordered]@{
                'P' = 'P '; 'V' = 'V '; 'REJECT EMPTY' = 'REJECT EMPTY'; 'REJECT UNSUPPORTED_HOST' = 'REJECT UNSUPPORTED_HOST'
                'REJECT MIX_PLAYLIST' = 'REJECT MIX_PLAYLIST'; 'REJECT UNRECOGNIZED' = 'REJECT UNRECOGNIZED'
            }
            foreach ($name in $groups.Keys) {
                $prefix = $groups[$name]
                $count = @($answers | Where-Object { $_ -and $_.StartsWith($prefix) }).Count
                Test-Share 'C' "answer $name" $count $total 0.05
            }
        }
    }
}

# ---- comparison folding: kind -> script block (case fields, answer) -> the answer to compare ----
# true when a field's hex holds U+03A3 at a unit boundary
function Test-HasCapitalSigma([string]$field) {
    if ($field -ceq '-' -or $field -ceq '.') { return $false }
    for ($i = 0; $i + 4 -le $field.Length; $i += 4) { if ($field.Substring($i, 4) -ceq '03a3') { return $true } }
    return $false
}
function Format-FoldedSigma([string]$answer) {
    if ($null -eq $answer -or -not $answer.StartsWith('OK ')) { return $answer }
    $hex = $answer.Substring(3)
    $sb = [System.Text.StringBuilder]::new($answer.Length)
    [void]$sb.Append('OK ')
    for ($i = 0; $i + 4 -le $hex.Length; $i += 4) {
        $unit = $hex.Substring($i, 4)
        [void]$sb.Append($(if ($unit -ceq '03c2') { '03c3' } else { $unit }))
    }
    if ($hex.Length % 4 -ne 0) { [void]$sb.Append($hex.Substring($hex.Length - ($hex.Length % 4))) }
    return $sb.ToString()
}
$Folding = @{
    S = @{
        Note = 'S: op lower on an input with U+03A3 is compared modulo the final-sigma form (U+03C2 folded to U+03C3 in both answers); all else exactly'
        Fold = { param($fields, $answer, $side) if ($fields[0] -ceq 'lower' -and (Test-HasCapitalSigma $fields[1])) { Format-FoldedSigma $answer } else { $answer } }
    }
    W = @{
        Note = 'W: op jb is compared with its two known differences aligned (Format-JbFolded: a percent that is not finite in the Kotlin answer is unknown; the tail of an ItemFailed after a put that answered AlreadyExists with a non-empty text of its own is dropped in both answers); every other op and all else exactly'
        Fold = { param($fields, $answer, $side) if ($fields[0] -ceq 'jb' -and $null -ne $answer) { Format-JbFolded $fields $answer $side } else { $answer } }
    }
}

