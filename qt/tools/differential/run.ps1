# Runs a program with stdin from a file (or none) and returns its stdout lines; a non-zero exit code is an error.
function Invoke-Side([string]$exe, [string[]]$arguments, [string]$inputFile, [string]$name) {
    $outFile = Join-Path $work "$name.out"
    $errFile = Join-Path $work "$name.err"
    $quoted = $arguments | ForEach-Object { '"' + $_ + '"' }
    $options = @{ FilePath = $exe; ArgumentList = $quoted; RedirectStandardOutput = $outFile; RedirectStandardError = $errFile
                  NoNewWindow = $true; Wait = $true; PassThru = $true }
    if ($inputFile) { $options.RedirectStandardInput = $inputFile }
    $process = Start-Process @options
    if ($process.ExitCode -ne 0) { throw "$name failed ($($process.ExitCode)): $(Get-Content -Raw $errFile)" }
    $lines = [System.IO.File]::ReadAllLines($outFile, [System.Text.Encoding]::ASCII)
    Remove-Item -LiteralPath $outFile
    return , $lines
}
