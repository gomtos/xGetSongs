$EndPairHexPattern = [regex]::new('d[89ab][0-9a-f]{2}d[c-f][0-9a-f]{2}$', 'Compiled')
# the measures shared by L and Y: surrogates, length over 30000 units, answers that end next to the cut
function Test-LyricsCommon([string]$kind, $cases, $answers) {
    $total = $cases.Count
    $pair = 0; $lone = 0; $long = 0; $endPair = 0; $atLimit = 0
    for ($i = 0; $i -lt $total; $i++) {
        $field = $cases[$i][0]
        if ($PairHexPattern.IsMatch($field)) { $pair++ }
        if ($LoneHexPattern.IsMatch($field)) { $lone++ }
        if ((Get-UnitCount $field) -gt 30000) {
            $long++
            $answer = $answers[$i]
            if ($answer -and $answer.StartsWith('OK ')) {
                $units = ($answer.Length - 3) / 4
                if ($EndPairHexPattern.IsMatch($answer)) { $endPair++ }
                if ($units -ge 29997 -and $units -le 30000) { $atLimit++ }
            }
        }
    }
    Test-Share $kind 'input with a surrogate pair' $pair $total 0.05
    Test-Share $kind 'input with an unpaired surrogate' $lone $total 0.02
    Test-Share $kind 'input over 30000 units' $long $total 0.02
    Test-Share $kind 'input over 30000 units, answer ends with a surrogate pair' $endPair $total 0.003
    Test-Share $kind 'input over 30000 units, answer of 29997..30000 units' $atLimit $total 0.003
}
