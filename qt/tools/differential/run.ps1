# The differential test of the Qt port: the same cases go to the Kotlin originals on the JVM (Oracle.java, on the jars of
# server/build/sidecar-image) and to the C++ ports (build/qt/xgs-diff.exe); the answers must be identical, line for line.
#
#   pwsh qt/tools/differential/run.ps1 [-Kinds UXMSCFDGTLYRNBZHOJEQVKAIWP] [-PerKind 10000] [-Seed 20261115] [-DebugTool]
#   (the default: all kinds)
#
# -DebugTool: the debug build's tool (build/qt-debug/xgs-diff.exe, where Qt's range checks and assertions are on) also answers
# every kind: the same generated cases (or, for a table kind, the same table mode), and its answers must be identical to the
# release tool's, line for line (no oracle involved). A difference, a non-zero exit of the debug tool, or a debug executable
# that is missing or older than the release one fails the run (exit code 1).
#
# Kinds U, X, M, B and Z have no cases: the two sides each print a table (unicodecase, chartable, constants, lettertable,
# nfkctable) and the tables are compared. Every other kind is generated by `xgs-diff gen`. The kinds are run one at a time
# and each kind's data is released before the next, so that all kinds fit in memory at -PerKind 100000. The exit code is 0 only when, for every kind, the
# answer counts match, no answer differs and the kind's statistics reach their thresholds ($Statistics below). Input and
# output are ASCII. Before anything else the script checks that the oracle's jars are not older than their sources
# (shared-jvm.jar against shared/src/commonMain, engine.jar against engine/src/main).
#
# One deliberate exception: for kind S op `lower`, when the case's input contains U+03A3 (capital sigma), both answers are
# compared after folding U+03C2 to U+03C3 ($Folding below, here and nowhere else): the final sigma form that Kotlin picks
# differs from xgs::kt's approximation of Unicode's Final_Sigma rule in some contexts (qt/README.md). Every other case, op
# and character is compared exactly.
#
# Adding a kind: a generator (gen.cpp, registerGenerators), an answerer (main.cpp, registerAnswers), a `case` in
# Oracle.java, and the kind's thresholds in $Statistics here. A kind without an entry in $Statistics fails.
