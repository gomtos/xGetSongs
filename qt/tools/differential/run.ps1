function Get-LyricsKey([string]$line) { $NotLetterOrDigit.Replace($line, '').ToLowerInvariant() }
function Test-LyricsHeading([string]$line) {
    $trimmed = $line.Trim($KotlinWhitespace)
    -not $HashtagLine.IsMatch($trimmed) -and $LyricsMarkers.Contains((Get-LyricsKey $line))
}
# 0 for a lyric line, else 1..7: the kind of terminator ($TerminatorKinds), in the order of isTerminator
function Get-TerminatorKind([string]$line) {
    $t = $line.Trim($KotlinWhitespace)
    if ($SeparatorLine.IsMatch($t)) { return 1 }
    if ($LinkMarker.IsMatch($t)) { return 2 }
    if ($CopyrightPrefix.IsMatch($t)) { return 3 }
    if ($HashtagLine.IsMatch($t)) { return 4 }
    $k = Get-LyricsKey $t
    if ($BoilerplateKey.IsMatch($k)) { return 5 }
    if ($t.Length -ge 2 -and (($t[0] -ceq '[' -and $t[-1] -ceq ']') -or ($t[0] -ceq '【' -and $t[-1] -ceq '】'))) {
        if ($LyricsMarkers.Contains($k) -or $OtherSectionKey.IsMatch($k)) { return 6 }
        return 0
    }
    if ($t.Length -ge 2 -and $t[0] -ceq '(' -and $t[-1] -ceq ')' -and $ParenthesisedHeadings.Contains($k)) { return 7 }
    return 0
}
