function Get-LyricsStringFields($case) {
    switch -CaseSensitive ($case[0]) {
        'match' { return @(1, 2, 3, 5, 6, 7, 10) }
        'pick' {
            $fields = [System.Collections.Generic.List[int]]::new([int[]]@(1, 2, 3))
